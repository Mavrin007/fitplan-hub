import type { ReactNode } from "react";
import type { RingColor } from "./colors";

/** Одно кольцо из композита RingProgress (количество колец = длине data).
 *  Каждое кольцо само описывает цвет, толщину и прогресс — композит не знает
 *  про конкретные метрики, поэтому набор колец меняется без правки логики. */
export interface RingDatum {
  /** Стабильный ключ (React key + суффикс id SVG-градиентов). */
  id: string;
  /** Подпись кольца: «Калории», «Тренировки», «Вода». */
  label: string;
  /** Текущее значение. Может превышать max — тогда рисуется второй круг. */
  value: number;
  /** Целевое значение (100 %). */
  max: number;
  /** Единица измерения для aria-метки и деталей («ккал», «мин», «л»). */
  unit: string;
  /** Палитра кольца (базовый цвет, градиент, свечение, трек). */
  color: RingColor;
  /** Цвет «перелива» при value > max: хвост второго круга, капля на нём и
   *  тонировка трека. Без него перебор рисуется цветом кольца (Apple-стиль). */
  overColor?: string;
  /** Цвет капли (по умолчанию: overColor при переборе, иначе base). */
  tipColor?: string;
  /** Толщина дуги в px. По умолчанию — из шкалы композита (по позиции). */
  stroke?: number;
  /** Явный радиус (px); по умолчанию радиусы считаются концентрично. */
  radius?: number;
  /** Формат значения для центральных деталей (например, литры «2,3»).
   *  По умолчанию — целое число с разделителями. */
  display?: (value: number) => string;
}

/** Пропсы композита из трёх концентрических колец. */
export interface RingProgressProps {
  /** Кольца от внешнего к внутреннему. */
  data: RingDatum[];
  /** Внешний диаметр композита в px. */
  size?: number;
  /** Зазор между кольцами в px (не влияет на явные radius). */
  gap?: number;
  /** Длительность анимации «докручивания» в секундах. */
  duration?: number;
  /** Базовая задержка старта; каждое следующее кольцо +0.12 с. */
  delay?: number;
  /** Подпись в центре (по умолчанию «Сегодня»). */
  caption?: string;
  /** Кастомное содержимое центра (переопределяет percent + caption). */
  center?: ReactNode;
  /** Aria-подпись всего композита. */
  "aria-label"?: string;
  className?: string;
}

/** Строка детали для центральной подсказки при наведении. */
export interface RingDetail {
  label: string;
  /** Отформатированная пара «значение / цель» (например «742 / 800»). */
  value: string;
  color: string;
}
